def sidebar() -> Optional[Dict]:
    st.sidebar.title("ðŸ›¡ï¸ Detection console")
    st.sidebar.caption("Hybrid IDS: signature rules + Isolation Forest + Random Forest")

    pcaps = available_pcaps()
    options = {p.stem: p for p in pcaps}

    st.sidebar.subheader("1 Â· Traffic data")
    choice = st.sidebar.selectbox(
        "Bundled capture",
        options=list(options.keys()),
        help="Generated by data/generate_dataset.py",
    )

    uploaded = st.sidebar.file_uploader("â€¦or upload a .pcap", type=["pcap", "cap"])

    st.sidebar.subheader("2 Â· Detection thresholds")
    window = st.sidebar.slider("Aggregation window (s)", 5.0, 30.0, 10.0, 1.0)
    scan_ports = st.sidebar.slider("Port-scan threshold (distinct ports)", 5, 60, 15)
    min_severity = st.sidebar.select_slider(
        "Minimum severity to report", options=["INFO", "LOW", "MEDIUM", "HIGH", "CRITICAL"],
        value="LOW",
    )

    st.sidebar.subheader("3 Â· Run")
    run = st.sidebar.button("â–¶ Analyse traffic", type="primary", width="stretch")

    if not run:
        return None

    pcap_path = options.get(choice)
    if uploaded is not None:
        tmp = Path(tempfile.gettempdir()) / uploaded.name
        tmp.write_bytes(uploaded.getbuffer())
        pcap_path = tmp

    if pcap_path is None:
        st.sidebar.error("No capture selected.")
        return None

    with st.spinner("Extracting flows and scoring them..."):
        return run_analysis(str(pcap_path), window, scan_ports, min_severity)



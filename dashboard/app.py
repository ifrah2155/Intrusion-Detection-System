def overview(data: Dict) -> None:
    alerts = data["alerts"]
    flows = data["flows"]

    counts: Dict[str, int] = {}
    for alert in alerts:
        counts[alert["severity"]] = counts.get(alert["severity"], 0) + 1

    cols = st.columns(5)
    cols[0].metric("Flows analysed", f"{len(flows):,}")
    cols[1].metric("Alerts", len(alerts))
    cols[2].metric("Critical", counts.get("CRITICAL", 0))
    cols[3].metric("High", counts.get("HIGH", 0))
    cols[4].metric("Medium", counts.get("MEDIUM", 0))

    if not alerts:
        st.success(
            "No alerts raised for this capture. That is the expected result for "
            "the benign baseline (Scenario 1)."
        )


def timeline_chart(alerts: List[Dict]) -> alt.Chart:
    df = pd.DataFrame(
        [
            {
                "seconds": a["timestamp"] - alerts[0]["timestamp"] if alerts else 0,
                "severity": a["severity"],
                "rank": SEVERITY_ORDER.get(a["severity"], 0),
                "rule": a["rule_name"],
                "flows": a["flow_count"],
                "id": a["alert_id"],
            }
            for a in alerts
        ]
    )

    return (
        alt.Chart(df)
        .mark_circle(opacity=0.85, stroke="white", strokeWidth=1)
        .encode(
            x=alt.X("seconds:Q", title="seconds since first alert"),
            y=alt.Y("rank:O", title=None,
                    scale=alt.Scale(domain=[0, 1, 2, 3, 4])),
            size=alt.Size("flows:Q", title="flows in incident", scale=alt.Scale(range=[60, 900])),
            color=alt.Color("severity:N", scale=alt.Scale(
                domain=list(SEVERITY_COLOUR), range=list(SEVERITY_COLOUR.values()))),
            tooltip=["id", "rule", "severity", "flows", "seconds"],
        )
        .properties(height=260, title="Alert timeline")
    )


def severity_bar(alerts: List[Dict]) -> alt.Chart:
    df = pd.DataFrame([{"severity": a["severity"], "rule": a["rule_name"]} for a in alerts])
    counts = df.groupby(["rule", "severity"]).size().reset_index(name="count")

    return (
        alt.Chart(counts)
        .mark_bar()
        .encode(
            x=alt.X("count:Q", title="alerts"),
            y=alt.Y("rule:N", sort="-x", title=None),
            color=alt.Color("severity:N", scale=alt.Scale(
                domain=list(SEVERITY_COLOUR), range=list(SEVERITY_COLOUR.values()))),
            tooltip=["rule", "severity", "count"],
        )
        .properties(height=max(140, 26 * len(counts)), title="Alerts by rule")
    )


def feature_chart(features: List[Dict]) -> alt.Chart:
    df = pd.DataFrame(features)
    return (
        alt.Chart(df)
        .mark_bar()
        .encode(
            x=alt.X("contribution:Q", title="contribution (|z| Ã— importance)"),
            y=alt.Y("label:N", sort="-x", title=None),
            color=alt.Color("z_score:Q", scale=alt.Scale(scheme="redblue", domainMid=0),
                            title="z-score"),
            tooltip=["label", "value", "benign_mean", "z_score", "contribution"],
        )
        .properties(height=max(160, 30 * len(df)), title="Why is this anomalous?")
    )


def alert_detail(alert: Dict) -> None:
    icon = SEVERITY_ICON.get(alert["severity"], "")
    st.subheader(f"{icon} {alert['alert_id']} Â· {alert['rule_name']} Â· {alert['severity']}")

    left, mid, right = st.columns([2, 2, 1])
    left.markdown(
        f"**Source**  `{alert['src_ip']}:{alert['src_port']}`  \n"
        f"**Target**  `{alert['dst_ip']}:{alert['dst_port']}` ({alert['proto']})  \n"
        f"**Flows**  {alert['flow_count']}"
    )
    mid.markdown(
        f"**Time**  {alert['time_utc']} UTC  \n"
        f"**Confidence**  {alert['confidence']:.2f}  \n"
        f"**Layers**  {', '.join(alert['detection_layers'])}"
    )
    right.markdown(
        f"**Ground truth**  \n`{alert['ground_truth']}`  \n"
        f"**Category**  \n`{alert['category']}`"
    )

    st.info(alert["explanation"])

    tabs = st.tabs(["Evidence", "ML attribution", "Affected flows", "Raw alert"])

    with tabs[0]:
        evidence = alert.get("evidence", {})
        rows = []
        for key, value in evidence.items():
            if isinstance(value, dict):
                value = ", ".join(f"{k}={v}" for k, v in value.items())
            rows.append({"signal": key, "value": value})
        st.dataframe(pd.DataFrame(rows), width="stretch", hide_index=True)

        ml = alert.get("ml", {})
        st.caption(
            f"Isolation Forest {ml.get('if_score', 0):.2f} Â· Random Forest "
            f"{ml.get('rf_attack_prob', 0):.2f} Â· {ml.get('note', '')}"
        )

    with tabs[1]:
        features = alert.get("ml", {}).get("top_features", [])
        if features:
            st.altair_chart(feature_chart(features), width="stretch")
            st.caption(
                "Each bar is |z-score against the benign baseline| Ã— the model's "
                "global feature importance, so both ingredients are inspectable."
            )
        else:
            st.write("No ML attribution available (signature-only detection).")

    with tabs[2]:
        flows = st.session_state.get("flows")
        keys = alert.get("flow_keys", [])
        if flows is not None and keys:
            subset = flows[flows["flow_key"].isin(keys)]
            columns = [c for c in (
                "src_ip", "dst_ip", "src_port", "dst_port", "proto_name",
                "total_packets", "total_bytes", "duration", "syn_ratio",
                "src_unique_dst_ports_win", "if_score", "rf_attack_prob", "label",
            ) if c in subset.columns]
            st.dataframe(subset[columns], width="stretch", hide_index=True)
        else:
            st.write("Layer-2 (ARP) alert: no IP flows to show.")

    with tabs[3]:
        st.json(alert)


def alerts_tab(data: Dict) -> None:
    alerts = data["alerts"]
    if not alerts:
        return

    frame = pd.DataFrame(
        [
            {
                "": SEVERITY_ICON.get(a["severity"], ""),
                "id": a["alert_id"],
                "time": a["time_utc"],
                "severity": a["severity"],
                "rule": a["rule_name"],
                "category": a["category"],
                "source": a["src_ip"],
                "target": f"{a['dst_ip']}:{a['dst_port']}",
                "flows": a["flow_count"],
                "confidence": a["confidence"],
                "layers": "+".join(a["detection_layers"]),
                "truth": a["ground_truth"],
            }
            for a in alerts
        ]
    )

    st.dataframe(frame, width="stretch", hide_index=True, height=280)

    c1, c2 = st.columns(2)
    with c1:
        st.altair_chart(severity_bar(alerts), width="stretch")
    with c2:
        st.altair_chart(timeline_chart(alerts), width="stretch")

    st.divider()
    selected = st.selectbox(
        "Inspect an alert",
        options=[a["alert_id"] for a in alerts],
        format_func=lambda x: f"{x} Â· {next(a['rule_name'] for a in alerts if a['alert_id'] == x)}",
    )
    alert = next(a for a in alerts if a["alert_id"] == selected)
    alert_detail(alert)


def evaluation_tab() -> None:
    path = RESULTS_DIR / "evaluation.json"
    if not path.exists():
        st.info("Run `python -m nids evaluate` to populate the evaluation view.")
        return

    summary = json.loads(path.read_text(encoding="utf-8"))

    st.subheader("Flow-level performance")
    rows = []
    for layer in ("signature", "ml", "hybrid"):
        m = summary["overall"].get(layer)
        if m:
            rows.append({
                "layer": layer, "TP": m["tp"], "FP": m["fp"], "TN": m["tn"], "FN": m["fn"],
                "precision": m["precision"], "recall": m["recall"],
                "f1": m["f1"], "accuracy": m["accuracy"],
            })
    st.dataframe(pd.DataFrame(rows), width="stretch", hide_index=True)

    st.subheader("Per scenario")
    st.dataframe(pd.DataFrame(summary["per_scenario"]), width="stretch", hide_index=True)

    st.subheader("Per attack class")
    rows = []
    for label, entry in summary["per_attack_class"].items():
        rows.append({
            "attack": label,
            "flows": entry["flows"],
            "signature recall": entry.get("signature", {}).get("recall", 0),
            "ml recall": entry.get("ml", {}).get("recall", 0),
            "hybrid recall": entry.get("hybrid", {}).get("recall", 0),
        })
    st.dataframe(pd.DataFrame(rows), width="stretch", hide_index=True)

    charts = RESULTS_DIR / "confusion_matrices.png"
    if charts.exists():
        st.image(str(charts), caption="Flow-level confusion matrices")



def main() -> None:
    st.title("AI-Driven Network Traffic Analysis & Intrusion Detection")

    data = sidebar()

    if data is None:
        st.markdown(
            """
### What this does

This console ingests a packet capture, reconstructs **bidirectional flows**,
extracts **55 behavioural features** (rates, flag ratios, packet-size
distributions, per-window scan/fan-in statistics), and runs two independent
detection layers:

| Layer | Method | Role |
|---|---|---|
| **Signature** | 9 deterministic rules (R-001 â€¦ R-008) | high-precision, fully explainable |
| **ML** | Isolation Forest + Random Forest | generalisation to unseen behaviour |

Alerts from both layers are **fused into incidents**, scored by severity, and
each one carries the evidence, thresholds and ML feature attributions that
justify it.

**Pick a capture in the sidebar and press _Analyse traffic_.**
            """
        )
        scenario_table = pd.DataFrame(
            [{"capture": k, "contains": v} for k, v in DEFAULT_SCENARIOS.items()]
        )
        st.dataframe(scenario_table, width="stretch", hide_index=True)
        return

    st.caption(f"Capture: `{data['pcap']}`")
    overview(data)

    st.session_state["flows"] = data["flows"]

    tab_alerts, tab_flows, tab_eval = st.tabs(
        ["ðŸš¨ Alerts", "ðŸ“Š All flows", "ðŸ“ˆ Evaluation"]
    )

    with tab_alerts:
        alerts_tab(data)

    with tab_flows:
        flows = data["flows"]
        columns = [c for c in (
            "src_ip", "dst_ip", "dst_port", "proto_name", "total_packets",
            "total_bytes", "duration", "syn_ratio", "src_unique_dst_ports_win",
            "dst_unique_src_hosts_win", "if_score", "rf_attack_prob",
            "alert_id", "flow_severity", "label",
        ) if c in flows.columns]
        st.dataframe(flows[columns], width="stretch", hide_index=True, height=520)
        st.download_button(
            "Download flows as CSV",
            flows.to_csv(index=False).encode("utf-8"),
            file_name=f"{data['scenario']}.flows.csv",
            mime="text/csv",
        )

    with tab_eval:
        evaluation_tab()


if __name__ == "__main__":
    main()

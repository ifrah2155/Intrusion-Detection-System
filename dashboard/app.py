@st.cache_resource(show_spinner=False)
def get_model():
    return load_model()


@st.cache_data(show_spinner=False)
def run_analysis(pcap_path: str, window: float, scan_ports: int,
                 min_severity: str) -> Dict:
    config = DetectionConfig().with_overrides(
        window_seconds=float(window),
        scan_unique_ports=int(scan_ports),
        report_min_severity=min_severity,
    )
    result = analyse_pcap(pcap_path, config=config, model=get_model())

    return {
        "scenario": result.scenario,
        "pcap": result.pcap,
        "alerts": [a.to_dict() for a in result.alerts],
        "flows": result.flows,
        "alerts_frame": result.alerts_frame(),
    }


